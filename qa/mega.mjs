import { chromium } from '@playwright/test';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
const p = await b.newPage({ viewport: { width: 1440, height: 800 } });
await p.goto('http://localhost:3100/', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: 'What we do menu' }).click();
await p.screenshot({ path: 'qa/screenshots/mega-1440.png' });
const m = await b.newPage({ viewport: { width: 375, height: 812 } });
await m.goto('http://localhost:3100/', { waitUntil: 'networkidle' });
await m.locator('.menu-btn').click(); await m.locator('.m-toggle', { hasText: 'What we do' }).click();
await m.screenshot({ path: 'qa/screenshots/menu-375.png' });
await b.close();
